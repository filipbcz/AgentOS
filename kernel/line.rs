//! Bounded canonical ASCII input, independent of the UART and user memory.
//!
//! A completed record contains at most 255 edited bytes plus LF. Ctrl-D queues
//! one EOF only when the edit buffer is empty. With pending input it rings the
//! bell and preserves that input; Enter submits it without an ambiguous partial
//! record boundary in the native byte-stream read API.
//! Overflow or lost UART data invalidates *all* queued and partial input and
//! latches one overflow event. Bytes through the next CR/LF are discarded, so a
//! truncated command can never become a new record. Consumers must also discard
//! any command prefix already returned by an earlier short read on overflow.
#![allow(non_snake_case)]

pub const MAX_LINE: usize = 255;
pub const RECORD_BYTES: usize = MAX_LINE + 1;
const QUEUED_LINES: usize = 4;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Echo { fBytes: [u8; 3], fLength: usize }

impl Echo {
    const NONE: Self = Self { fBytes: [0; 3], fLength: 0 };
    const NEWLINE: Self = Self { fBytes: [b'\r', b'\n', 0], fLength: 2 };
    const ERASE: Self = Self { fBytes: [8, b' ', 8], fLength: 3 };
    const BELL: Self = Self { fBytes: [7, 0, 0], fLength: 1 };
    const LOST_LINE: Self = Self { fBytes: [b'\r', b'\n', 7], fLength: 3 };

    pub fn asBytes(&self) -> &[u8] { &self.fBytes[..self.fLength] }
}

#[derive(Debug, PartialEq, Eq)]
pub enum Read<'a> { Data(&'a [u8]), Eof, Overflow }

#[derive(Clone, Copy)]
struct Record { fBytes: [u8; RECORD_BYTES], fLength: usize }

impl Record {
    const fn new() -> Self { Self { fBytes: [0; RECORD_BYTES], fLength: 0 } }
}

pub struct LineInput {
    fEdit: [u8; MAX_LINE],
    fEditLength: usize,
    fRecords: [Record; QUEUED_LINES],
    fHead: usize,
    fCount: usize,
    fOffset: usize,
    fOverflow: bool,
    fDiscarding: bool,
    fIgnoreLf: bool,
}

impl LineInput {
    pub const fn new() -> Self {
        Self {
            fEdit: [0; MAX_LINE], fEditLength: 0,
            fRecords: [Record::new(); QUEUED_LINES],
            fHead: 0, fCount: 0, fOffset: 0,
            fOverflow: false, fDiscarding: false, fIgnoreLf: false,
        }
    }

    /// Hardware loss and software overflow share a fail-closed recovery path.
    /// Repeated losses coalesce into one pending error, without retaining data.
    pub fn invalidate(&mut self) {
        self.fEditLength = 0;
        self.fHead = 0;
        self.fCount = 0;
        self.fOffset = 0;
        self.fOverflow = true;
        self.fDiscarding = true;
        self.fIgnoreLf = false;
    }

    fn enqueue(&mut self, aNewline: bool) -> bool {
        if self.fCount == QUEUED_LINES {
            self.invalidate();
            // The CR/LF causing this enqueue already ended the lost line.
            // Ctrl-D is not a CR/LF delimiter, so its failure stays quarantined.
            if aNewline { self.fDiscarding = false; }
            return false;
        }
        let pTail = (self.fHead + self.fCount) % QUEUED_LINES;
        let pRecord = &mut self.fRecords[pTail];
        pRecord.fBytes[..self.fEditLength].copy_from_slice(&self.fEdit[..self.fEditLength]);
        pRecord.fLength = self.fEditLength;
        if aNewline {
            pRecord.fBytes[pRecord.fLength] = b'\n';
            pRecord.fLength += 1;
        }
        self.fEditLength = 0;
        self.fCount += 1;
        true
    }

    /// Return only the short echo generated by this byte; no device I/O occurs.
    pub fn push(&mut self, aByte: u8) -> Echo {
        if self.fIgnoreLf {
            self.fIgnoreLf = false;
            if aByte == b'\n' { return Echo::NONE; }
        }
        if aByte == b'\r' || aByte == b'\n' {
            let pEcho = if self.fDiscarding {
                self.fDiscarding = false;
                Echo::NEWLINE
            } else if self.enqueue(true) {
                Echo::NEWLINE
            } else {
                Echo::LOST_LINE
            };
            self.fIgnoreLf = aByte == b'\r';
            return pEcho;
        }
        if self.fDiscarding { return Echo::NONE; }
        match aByte {
            4 => {
                if self.fEditLength != 0 { return Echo::BELL; }
                if self.enqueue(false) { Echo::NONE } else { Echo::BELL }
            }
            8 | 127 => {
                if self.fEditLength == 0 { return Echo::NONE; }
                self.fEditLength -= 1;
                Echo::ERASE
            }
            b'\t' | b' '..=b'~' => {
                if self.fEditLength == MAX_LINE {
                    self.invalidate();
                    return Echo::BELL;
                }
                let pByte = if aByte == b'\t' { b' ' } else { aByte };
                self.fEdit[self.fEditLength] = pByte;
                self.fEditLength += 1;
                Echo { fBytes: [pByte, 0, 0], fLength: 1 }
            }
            _ => Echo::NONE,
        }
    }

    pub fn ready(&self) -> bool { self.fOverflow || self.fCount != 0 }

    /// Inspect one record without consuming it, so the caller can first validate
    /// the entire user destination. Zero capacity never exposes or consumes an
    /// event. A pending overflow precedes any valid data received after recovery.
    pub fn peek(&self, aLimit: usize) -> Option<Read<'_>> {
        if aLimit == 0 { return None; }
        if self.fOverflow { return Some(Read::Overflow); }
        if self.fCount == 0 { return None; }
        let pRecord = &self.fRecords[self.fHead];
        if pRecord.fLength == 0 { return Some(Read::Eof); }
        let pCount = aLimit.min(pRecord.fLength - self.fOffset);
        Some(Read::Data(&pRecord.fBytes[self.fOffset..self.fOffset + pCount]))
    }

    /// Advance only after a successful copy. Zero acknowledges an EOF or error;
    /// a zero-byte consumption of a data record leaves it unchanged.
    pub fn consume(&mut self, aCount: usize) {
        if self.fOverflow {
            assert!(aCount == 0);
            self.fOverflow = false;
            return;
        }
        assert!(self.fCount != 0);
        let pLength = self.fRecords[self.fHead].fLength;
        assert!(aCount <= pLength - self.fOffset);
        self.fOffset += aCount;
        if self.fOffset == pLength {
            self.fHead = (self.fHead + 1) % QUEUED_LINES;
            self.fCount -= 1;
            self.fOffset = 0;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn feed(aInput: &mut LineInput, aBytes: &[u8]) {
        for &pByte in aBytes { aInput.push(pByte); }
    }

    fn expectData(aInput: &mut LineInput, aExpected: &[u8], aLimit: usize) {
        assert_eq!(aInput.peek(aLimit), Some(Read::Data(aExpected)));
        aInput.consume(aExpected.len());
    }

    #[test]
    fn editingAndShortReads() {
        let mut pInput = LineInput::new();
        feed(&mut pInput, b"echp\x08o\tx\x7fvalue\r\n");
        expectData(&mut pInput, b"ech", 3);
        expectData(&mut pInput, b"o value\n", RECORD_BYTES);
        assert!(!pInput.ready());
    }

    #[test]
    fn echoMatchesAcceptedEdits() {
        let mut pInput = LineInput::new();
        assert_eq!(pInput.push(8).asBytes(), b"");
        assert_eq!(pInput.push(b'a').asBytes(), b"a");
        assert_eq!(pInput.push(b'\t').asBytes(), b" ");
        assert_eq!(pInput.push(127).asBytes(), b"\x08 \x08");
        assert_eq!(pInput.push(b'\r').asBytes(), b"\r\n");
        assert_eq!(pInput.push(b'\n').asBytes(), b"");
        expectData(&mut pInput, b"a\n", RECORD_BYTES);
    }

    #[test]
    fn exactlyFullLineAndZeroCapacity() {
        let mut pInput = LineInput::new();
        feed(&mut pInput, &[b'x'; MAX_LINE]);
        assert!(!pInput.ready());
        pInput.push(b'\n');
        assert!(pInput.ready());
        assert_eq!(pInput.peek(0), None);
        let mut pExpected = [b'x'; RECORD_BYTES];
        pExpected[MAX_LINE] = b'\n';
        expectData(&mut pInput, &pExpected, RECORD_BYTES);
        assert!(!pInput.ready());
    }

    #[test]
    fn overlongLineNeverReturnsPrefixOrSuffix() {
        let mut pInput = LineInput::new();
        feed(&mut pInput, b"queued\n");
        feed(&mut pInput, &[b'x'; MAX_LINE]);
        assert_eq!(pInput.push(b'y').asBytes(), b"\x07");
        assert_eq!(pInput.peek(1), Some(Read::Overflow));
        pInput.consume(0);
        assert!(!pInput.ready());
        feed(&mut pInput, b"suffix\x08\x04\n");
        assert!(!pInput.ready());
        feed(&mut pInput, b"valid\n");
        expectData(&mut pInput, b"valid\n", RECORD_BYTES);
    }

    #[test]
    fn fullQueueFlushesAndRecoversAtConsumedDelimiter() {
        let mut pInput = LineInput::new();
        for _ in 0..QUEUED_LINES { feed(&mut pInput, b"old\n"); }
        feed(&mut pInput, b"lost");
        assert_eq!(pInput.push(b'\r').asBytes(), b"\r\n\x07");
        feed(&mut pInput, b"\nnew\n");
        assert_eq!(pInput.peek(1), Some(Read::Overflow));
        pInput.consume(0);
        expectData(&mut pInput, b"new\n", RECORD_BYTES);
        assert!(!pInput.ready());
    }

    #[test]
    fn hardwareLossInvalidatesPartlyReadRecord() {
        let mut pInput = LineInput::new();
        feed(&mut pInput, b"partial command\n");
        expectData(&mut pInput, b"partial", 7);
        pInput.invalidate();
        assert_eq!(pInput.peek(16), Some(Read::Overflow));
        pInput.consume(0);
        feed(&mut pInput, b"unknown tail\r\nnext\n");
        expectData(&mut pInput, b"next\n", RECORD_BYTES);
        assert!(!pInput.ready());
    }

    #[test]
    fn overflowRemainsBeforeRecoveredData() {
        let mut pInput = LineInput::new();
        pInput.invalidate();
        pInput.invalidate();
        feed(&mut pInput, b"discard\nnew\n");
        assert_eq!(pInput.peek(0), None);
        assert_eq!(pInput.peek(16), Some(Read::Overflow));
        pInput.consume(0);
        expectData(&mut pInput, b"new\n", RECORD_BYTES);
        assert!(!pInput.ready());
    }

    #[test]
    fn eofIsOneShotAndPartialInputRequiresEnter() {
        let mut pInput = LineInput::new();
        pInput.push(4);
        assert_eq!(pInput.peek(1), Some(Read::Eof));
        pInput.consume(0);
        assert!(!pInput.ready());
        feed(&mut pInput, b"abc");
        assert_eq!(pInput.push(4).asBytes(), b"\x07");
        assert!(!pInput.ready());
        feed(&mut pInput, b"\n\x04");
        expectData(&mut pInput, b"ab", 2);
        expectData(&mut pInput, b"c\n", RECORD_BYTES);
        assert_eq!(pInput.peek(1), Some(Read::Eof));
        pInput.consume(0);
        assert!(!pInput.ready());
    }

    #[test]
    fn fullQueueAtEofRequiresRecoveryDelimiter() {
        let mut pInput = LineInput::new();
        for _ in 0..QUEUED_LINES { pInput.push(4); }
        pInput.push(4);
        assert_eq!(pInput.peek(1), Some(Read::Overflow));
        pInput.consume(0);
        feed(&mut pInput, b"discard\nnew\n");
        expectData(&mut pInput, b"new\n", RECORD_BYTES);
    }

    #[test]
    fn recordBoundariesAndRingWrapRemainIntact() {
        let mut pInput = LineInput::new();
        for _ in 0..3 {
            feed(&mut pInput, b"first\nsecond\n");
            expectData(&mut pInput, b"fi", 2);
            expectData(&mut pInput, b"rst\n", RECORD_BYTES);
            expectData(&mut pInput, b"second\n", RECORD_BYTES);
        }
        assert!(!pInput.ready());
    }

    #[test]
    fn peekAndZeroDataConsumptionAreNonDestructive() {
        let mut pInput = LineInput::new();
        feed(&mut pInput, b"data\n");
        assert_eq!(pInput.peek(3), Some(Read::Data(&b"dat"[..])));
        pInput.consume(0);
        assert_eq!(pInput.peek(RECORD_BYTES), Some(Read::Data(&b"data\n"[..])));
        expectData(&mut pInput, b"data\n", RECORD_BYTES);
    }

    #[test]
    fn ignoredControlsAndBlankLines() {
        let mut pInput = LineInput::new();
        feed(&mut pInput, &[0, 1, 3, 0x1b, 0x80, 0xff]);
        assert!(!pInput.ready());
        feed(&mut pInput, b"\r\n\n");
        expectData(&mut pInput, b"\n", RECORD_BYTES);
        expectData(&mut pInput, b"\n", RECORD_BYTES);
        assert!(!pInput.ready());
    }
}
